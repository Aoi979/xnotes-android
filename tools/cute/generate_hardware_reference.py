#!/usr/bin/env python3
"""Extract atom traits and full-domain hardware-layout goldens from real host CuTe.

No GPU execution. Compile small translation units serially, each under a 2 GiB limit.
"""
import argparse
import json
from pathlib import Path
import resource
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
MMA = [
    ('fma', 'UniversalFMA<float,float,float>', False, False),
    ('sm70_nt', 'SM70_8x8x4_F32F16F16F32_NT', False, False),
    ('sm70_tn', 'SM70_8x8x4_F32F16F16F32_TN', False, False),
    ('sm75_f16', 'SM75_16x8x8_F32F16F16F32_TN', False, False),
    ('sm80_f16', 'SM80_16x8x16_F32F16F16F32_TN', False, False),
    ('sm80_f16acc', 'SM80_16x8x16_F16F16F16F16_TN', False, False),
    ('sm80_bf16', 'SM80_16x8x16_F32BF16BF16F32_TN', False, False),
    ('sm80_tf32', 'SM80_16x8x8_F32TF32TF32F32_TN', False, False),
    ('sm80_f64', 'SM80_8x8x4_F64F64F64F64_TN', False, False),
    ('sm80_s8', 'SM80_16x8x32_S32S8S8S32_TN', False, False),
    ('sm90_f64', 'SM90_16x8x16_F64F64F64F64_TN', False, False),
    ('sm90_gmma_ss', 'SM90_64x16x16_F32F16F16_SS<GMMA::Major::K,GMMA::Major::K>', True, True),
    ('sm90_gmma_rs', 'SM90_64x16x16_F32F16F16_RS<GMMA::Major::K,GMMA::Major::K>', False, True),
]
COPY = [
    ('universal32', 'UniversalCopy<uint32_t>', 'uint32_t', 32),
    ('universal128', 'UniversalCopy<uint128_t>', 'uint16_t', 16),
    ('cp_async_ca', 'SM80_CP_ASYNC_CACHEALWAYS<uint128_t>', 'uint16_t', 16),
    ('cp_async_cg', 'SM80_CP_ASYNC_CACHEGLOBAL<uint128_t>', 'uint16_t', 16),
] + [(f'ldsm_n{x}', f'SM75_U32x{x}_LDSM_N', 'uint16_t', 16) for x in (1,2,4)] \
  + [(f'ldsm_t{x}', f'SM75_U16x{x*2}_LDSM_T', 'uint16_t', 16) for x in (1,2,4)] \
  + [(f'stsm_n{x}', f'SM90_U32x{x}_STSM_N', 'uint16_t', 16) for x in (1,2,4)]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--cutlass', type=Path, required=True)
    parser.add_argument('--cuda', type=Path, default=Path('/opt/cuda'))
    args = parser.parse_args()
    sha = subprocess.check_output(['git','-C',str(args.cutlass),'rev-parse','HEAD'], text=True).strip()
    def limit(): resource.setrlimit(resource.RLIMIT_AS, (2*1024**3, 2*1024**3))
    header = '''#include <cute/tensor.hpp>
#include <cute/atom/mma_atom.hpp>
#include <cute/atom/copy_atom.hpp>
#include <iostream>
using namespace cute;
template<class T> void field(T const& t) { print(t); std::cout<<"\\t"; }
template<class T> void map(T const& t) { field(t); for(int i=0;i<size(t);++i){if(i)std::cout<<",";std::cout<<static_cast<long long>(t(i));}std::cout<<"\\n"; }
'''
    def run(body):
        with tempfile.TemporaryDirectory(prefix='cute-hardware-') as d:
            p=Path(d); (p/'ref.cpp').write_text(header+'\nint main(){\n'+body+'\n}\n')
            cmd=['g++','-std=c++17','-O0','-I'+str(args.cutlass/'include'),'-I'+str(args.cuda/'include'),'-I'+str(args.cuda/'include/cccl'),'-I/usr/include/cccl',str(p/'ref.cpp'),'-o',str(p/'ref')]
            r=subprocess.run(cmd,text=True,capture_output=True,preexec_fn=limit)
            if r.returncode: raise RuntimeError(r.stderr[-12000:])
            return subprocess.check_output([str(p/'ref')],text=True).strip()
    mma=[]; copies=[]
    for ident,typ,ad,bd in MMA:
        out=run(f'using A=MMA_Atom<{typ}>;field(typename A::Shape_MNK{{}});field(typename A::ThrID{{}});field(typename A::LayoutA_TV{{}});field(typename A::LayoutB_TV{{}});print(typename A::LayoutC_TV{{}});')
        mma.append((ident,typ,*[s.replace('_','') for s in out.split('\t')],ad,bd))
        print('Atom:',ident,flush=True)
    for ident,typ,val,bits in COPY:
        out=run(f'using A=Copy_Atom<{typ},{val}>;field(typename A::ThrID{{}});field(typename A::ValLayoutSrc{{}});field(typename A::ValLayoutDst{{}});print(typename A::ValLayoutRef{{}});')
        copies.append((ident,typ,val,bits,*[s.replace('_','') for s in out.split('\t')]))
        print('Atom:',ident,flush=True)
    def kt(x): return str(x).lower() if isinstance(x,bool) else str(x) if isinstance(x,int) else json.dumps(x)
    generated='''// Generated by tools/cute/generate_hardware_reference.py. Do not hand-edit traits.
// NVIDIA CUTLASS %s; BSD-3-Clause, see assets/licenses/cutlass-cute.txt.
package com.xnotes.core.cute

object CuteAtoms {
    const val REFERENCE = "%s"
    val mma = listOf(
%s
    )
    val copy = listOf(
%s
    )
    fun mma(id: String) = mma.firstOrNull { it.id == id } ?: throw CuteException("atom")
    fun copy(id: String) = copy.firstOrNull { it.id == id } ?: throw CuteException("atom")
}
'''%(sha,sha,'\n'.join('        MmaAtom('+','.join(map(kt,row))+'),' for row in mma),'\n'.join('        CopyAtom('+','.join(map(kt,row))+'),' for row in copies))
    (ROOT/'app/src/main/java/com/xnotes/core/cute/CuteAtoms.kt').write_text(generated)
    # A second output verifies the Kotlin tiling algorithms, not just the catalogue.
    fixtures=[]
    mma_cases=[('fma','(4,8,1):(1,4,0)','(_,_,_)'),('sm70_nt','(2,2,1):(2,1,0)','(_,_,_)'),
               ('sm70_nt','(2,2,1):(2,1,0)','(32,32,4)'),('sm80_f16','(2,2,1):(1,2,0)','(_,_,_)'),
               ('sm80_f16','(1,2,2):(0,1,2)','(_,_,_)'),('sm80_f16','(2,2,1):(2,1,0)','((4,4,2):(1,8,4),16,16)'),
               ('sm80_tf32','(2,1,1):(1,0,0)','(_,_,_)'),('sm90_gmma_ss','(1,1,1):(0,0,0)','(_,_,_)')]
    # Reuse the syntax translator without importing the old script's CLI side effects.
    source=(ROOT/'tools/cute/generate_reference.py').read_text()
    scope={}; exec('import re\n'+source[source.index('def operand('):source.index('\ncases = []')],scope)
    operand=scope['operand']
    for ident,thr,perm in mma_cases:
        typ=next(x[1] for x in MMA if x[0]==ident)
        parts='C' if ident=='sm90_gmma_ss' else 'ABC'
        body=f'auto a=make_tiled_mma({typ}{{}},{operand(thr)},{operand(perm)});\n'
        for part in parts: body+=f'map(a.get_layout{part}_TV());\n'
        for part,line in zip(parts,run(body).splitlines()): fixtures.append('\t'.join(['mma',ident,thr,perm,part,line.replace('_','')]))
        print('TiledMMA:',ident,thr,perm,flush=True)
    copy_cases=[('universal32','(4,8):(8,1)','(2,2):(2,1)'),('universal128','(8,4):(4,1)','(1,8):(0,1)'),
                ('cp_async_ca','(4,8):(8,1)','(2,4):(4,1)'),('ldsm_n4','(8,4):(4,1)','(1,8):(0,1)'),
                ('ldsm_t4','(8,4):(4,1)','(1,8):(0,1)'),('ldsm_n1','(8,4):(1,8)','(2,1):(1,0)'),
                ('stsm_n2','(4,8):(1,4)','(4,1):(1,0)')]
    for ident,thr,val in copy_cases:
        _,typ,vt,_=next(x for x in COPY if x[0]==ident)
        body=f'auto a=make_tiled_copy(Copy_Atom<{typ},{vt}>{{}},{operand(thr)},{operand(val)});map(a.get_layoutS_TV());map(a.get_layoutD_TV());'
        for part,line in zip('SD',run(body).splitlines()): fixtures.append('\t'.join(['copy',ident,thr,val,part,line.replace('_','')]))
        print('TiledCopy:',ident,flush=True)
    (ROOT/'app/src/test/resources/cute/hardware.tsv').write_text('# CUTLASS '+sha+'\n'+'\n'.join(fixtures)+'\n')
    print('Wrote catalogue and',len(fixtures),'hardware mappings.',flush=True)

if __name__ == '__main__': main()
